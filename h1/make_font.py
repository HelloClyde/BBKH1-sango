"""Generate freely licensed Noto GBK glyphs at the engine's native cell sizes."""
from pathlib import Path
import os
import json
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parents[1]
fontpath=Path(os.environ.get('SANGO_FONT', ROOT/'assets/fonts/NotoSansCJKsc-Regular.otf'))
codes={i:chr(i) for i in range(32,127)}
for a in range(0xa1,0xf8):
    for b in range(0xa1,0xff):
        try: codes[(a<<8)|b]=bytes([a,b]).decode('gbk')
        except UnicodeDecodeError:pass
target=ROOT/'h1/font.inc'
sizes=(12,14,16,20,24)
fonts={n:ImageFont.truetype(str(fontpath),n) for n in range(4,25)}
glyph_checks=0
top_pad,extra_rows=4,8
with target.open('w',encoding='ascii') as out:
    out.write('/* Noto Sans CJK, SIL Open Font License 1.1; generated by make_font.py. */\n')
    out.write(f'enum {{ H1_FONT_TOP_PAD={top_pad}, H1_FONT_EXTRA_ROWS={extra_rows} }};\n')
    out.write('static const unsigned short font_codes[]={'+','.join(str(c) for c in codes)+'};\n')
    for size in sizes:
        height=size+extra_rows
        out.write(f'static const unsigned char font{size}[][{height*((size+7)//8)}]={{\n')
        for code,char in codes.items():
            # One nominal size and baseline per script, never shrink individual
            # glyphs. Extra storage rows retain accents and descenders; rendering
            # subtracts top_pad so the logical text origin stays unchanged.
            advance=size//2 if code<128 else size
            nominal=size-2 if code<128 else size
            font=fonts[nominal]
            b=font.getbbox(char)
            ref=fonts[size-2].getbbox('Ag') if code<128 else fonts[size].getbbox('国存')
            dy=top_pad+(size-(ref[3]-ref[1]))//2-ref[1]
            ink_width=b[2]-b[0]
            # Fit unusually wide Latin symbols horizontally at the same height.
            # Punctuation retains the bank baseline rather than being centered.
            dx=(advance-ink_width)//2-b[0]
            im=Image.new('1',(size,height))
            if ink_width>advance:
                wide=Image.new('1',(ink_width,height));ImageDraw.Draw(wide).text((-b[0],dy),char,font=font,fill=1)
                im.paste(wide.resize((advance,height),Image.Resampling.NEAREST),(0,0))
            else:
                ImageDraw.Draw(im).text((dx,dy),char,font=font,fill=1)
            # Compare against an oversized reference, including boundary ink.
            large=Image.new('1',(size*3,height*3));ImageDraw.Draw(large).text((max(dx,0)+size,dy+height),char,font=font,fill=1)
            if ink_width<=advance:
                assert sum(im.getdata())==sum(large.getdata()),(size,char,b,dx,dy)
            else:
                assert b[1]+dy>=0 and b[3]+dy<=height,(size,char,b,dy)
            glyph_checks+=1
            out.write('{'+','.join(str(b) for b in im.tobytes())+'},\n')
        out.write('};\n')
(ROOT/'reports/font-validation.json').write_text(json.dumps({'result':'passed','cell_sizes':sizes,'glyphs_per_size':len(codes),'uncropped_glyph_checks':glyph_checks,'uniform_cjk_font_pixels':{str(n):n for n in sizes},'extra_rows':extra_rows,'top_pad':top_pad,'method':'Uniform nominal CJK size and shared baseline per bank; extra vertical storage prevents clipping. Compare final bitmaps with oversized reference ink; wide symbols fit horizontally without changing font height.'},indent=2)+'\n',encoding='utf8')
print('Generated',len(codes),'GBK glyphs at',sizes,'with uniform size and baseline')
